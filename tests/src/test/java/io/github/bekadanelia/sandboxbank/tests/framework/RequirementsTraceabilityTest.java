package io.github.bekadanelia.sandboxbank.tests.framework;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.bekadanelia.sandboxbank.config.TestConfig;
import io.github.bekadanelia.sandboxbank.junit.Requirement;
import io.qameta.allure.Epic;
import io.qameta.allure.Feature;
import java.io.IOException;
import java.lang.reflect.Method;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.platform.commons.support.AnnotationSupport;
import org.junit.platform.commons.support.ReflectionSupport;

/**
 * Keeps docs/requirements.md and the tests honest with each other.
 *
 * <p>It reads the rule ids from the document and the {@link Requirement} annotations from the
 * compiled tests, checks them against each other in both directions and writes the resulting
 * matrix to target/traceability.md.
 */
@Tag("framework")
@Epic("Test framework")
@Feature("Traceability")
class RequirementsTraceabilityTest {

    private static final String TESTS_PACKAGE = "io.github.bekadanelia.sandboxbank.tests";
    /** A table row such as: | <a id="trf-05"></a>TRF-05 | A single transfer is at most ... | */
    private static final Pattern RULE_ROW = Pattern.compile(
            "^\\|\\s*(?:<a id=\"[^\"]+\"></a>)?([A-Z]+-\\d{2})\\s*\\|\\s*(.+?)\\s*\\|\\s*$");

    private static final Map<String, String> RULES = new LinkedHashMap<>();
    private static final Map<String, Set<String>> TESTS_BY_RULE = new TreeMap<>();

    @BeforeAll
    static void readRulesAndTests() throws IOException {
        for (String line : Files.readAllLines(TestConfig.requirementsFile())) {
            Matcher row = RULE_ROW.matcher(line);
            if (row.matches()) {
                RULES.put(row.group(1), row.group(2));
            }
        }
        for (Class<?> testClass : ReflectionSupport.findAllClassesInPackage(TESTS_PACKAGE, type -> true, name -> true)) {
            for (Method method : testClass.getDeclaredMethods()) {
                if (AnnotationSupport.isAnnotated(method, Test.class)
                        || AnnotationSupport.isAnnotated(method, ParameterizedTest.class)) {
                    String name = testClass.getName().substring(TESTS_PACKAGE.length() + 1) + "." + method.getName();
                    for (String id : requirementsOf(method, testClass)) {
                        TESTS_BY_RULE.computeIfAbsent(id, key -> new TreeSet<>()).add(name);
                    }
                }
            }
        }
        writeMatrix();
    }

    /** Ids on the method plus those on its class and on the classes around a nested class. */
    private static List<String> requirementsOf(Method method, Class<?> testClass) {
        List<String> ids = new ArrayList<>();
        AnnotationSupport.findAnnotation(method, Requirement.class).ifPresent(found -> ids.addAll(List.of(found.value())));
        for (Class<?> type = testClass; type != null; type = type.getEnclosingClass()) {
            AnnotationSupport.findAnnotation(type, Requirement.class).ifPresent(found -> ids.addAll(List.of(found.value())));
        }
        return ids;
    }

    private static void writeMatrix() throws IOException {
        StringBuilder matrix = new StringBuilder("""
                # Traceability matrix

                Generated by `RequirementsTraceabilityTest` from the `@Requirement` annotations in the test code.
                Do not edit by hand.

                | Rule | Tests | Covered by |
                |------|-------|------------|
                """);
        RULES.keySet().forEach(id -> {
            Set<String> tests = TESTS_BY_RULE.getOrDefault(id, Set.of());
            matrix.append("| [%s](requirements.md#%s) | %d | %s |%n".formatted(
                    id, id.toLowerCase(), tests.size(), String.join("<br>", tests).replace("$", ".")));
        });
        Path target = Path.of("target", "traceability.md");
        Files.createDirectories(target.getParent());
        Files.writeString(target, matrix);
    }

    @Test
    void the_requirements_document_can_be_read() {
        assertThat(RULES).as("rules found in %s", TestConfig.requirementsFile()).hasSizeGreaterThan(40);
    }

    @Test
    void every_rule_is_verified_by_at_least_one_test() {
        assertThat(RULES.keySet())
                .filteredOn(id -> !TESTS_BY_RULE.containsKey(id))
                .as("rules in docs/requirements.md that no test names in @Requirement")
                .isEmpty();
    }

    @Test
    void every_requirement_named_by_a_test_exists_in_the_document() {
        assertThat(TESTS_BY_RULE.keySet())
                .filteredOn(id -> !RULES.containsKey(id))
                .as("ids used in @Requirement that docs/requirements.md does not define")
                .isEmpty();
    }
}
